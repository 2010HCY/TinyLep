export let currentLang = 'en';

export function initI18n() {
    // 1. 读取系统语言
    const sysLang = navigator.language.toLowerCase();
    if (sysLang.startsWith('zh')) currentLang = 'zh';
    else if (sysLang.startsWith('es')) currentLang = 'es';
    else if (sysLang.startsWith('fr')) currentLang = 'fr';
    else if (sysLang.startsWith('ru')) currentLang = 'ru';
    else if (sysLang.startsWith('ar')) currentLang = 'ar';
    else if (sysLang.startsWith('ja')) currentLang = 'ja';
    else if (sysLang.startsWith('ko')) currentLang = 'ko';

    // 2. 绑定下拉框并侦听切换事件
    const selectEl = document.getElementById('lang-select');
    if (selectEl) {
        selectEl.value = currentLang;
        selectEl.addEventListener('change', (e) => {
            currentLang = e.target.value;
            applyLang();
        });
    }
    applyLang();
}

export function applyLang() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLang] && translations[currentLang][key]) {
            el.textContent = translations[currentLang][key];
        }
    });
}

// 供 JS 内部拼接字符时翻译使用
export function t(key) {
    return translations[currentLang][key] || key;
}